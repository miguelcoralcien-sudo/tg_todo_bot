"""
main.py — точка входа в Telegram-бота.

Здесь происходит:
1. Загрузка токена из .env-файла.
2. Создание и инициализация базы данных.
3. Настройка роутеров и диспетчера.
4. Запуск polling (постоянного опроса Telegram API).
"""

import asyncio
import logging
import os

from dotenv import load_dotenv
from aiogram import Bot, Dispatcher

# Импортируем базу данных и роутер с хендлерами
from database import Database
from handlers import handlers_router

# ===================================================================
# Настройка логирования
# ===================================================================

# Выводим в консоль сообщения уровня INFO и выше.
# Уровень DEBUG покажет ещё больше информации (полезно при отладке).
logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


# ===================================================================
# Основная функция запуска бота
# ===================================================================

async def main() -> None:
    """
    Основная асинхронная функция, которая запускает бота.

    Порядок действий:
    1. Загружаем токен из .env.
    2. Создаём объекты бота, диспетчера и базы данных.
    3. Создаём таблицу в БД, если её нет.
    4. Подключаем роутер с хендлерами.
    5. Запускаем polling — бот будет постоянно опрашивать Telegram API.
    """

    # ------------------------------------------------------------------
    # 1. Загрузка токена из .env
    # ------------------------------------------------------------------
    # load_dotenv() читает файл .env и добавляет переменные
    # в os.environ. После этого os.getenv() их видит.
    load_dotenv()

    # os.getenv("BOT_TOKEN") возвращает значение ключа BOT_TOKEN
    # или None, если ключ не найден.
    bot_token = os.getenv("BOT_TOKEN")

    if not bot_token:
        logger.error("Токен бота не найден! Создайте файл .env и добавьте туда BOT_TOKEN=<ваш_токен>")
        return

    logger.info("Токен бота успешно загружен из .env")

    # ------------------------------------------------------------------
    # 2. Создание объектов бота, диспетчера и базы данных
    # ------------------------------------------------------------------
    # Bot — объект, через который бот общается с Telegram API.
    # Парсинг разметки по умолчанию не задаём: текст задач приходит от людей,
    # и случайные теги вроде "<b>" сломали бы отправку сообщений.
    bot = Bot(token=bot_token)

    # Dispatcher — «центральный мозг» бота. Он получает обновления
    # от Telegram и направляет их к нужным обработчикам (хендлерам).
    dp = Dispatcher()

    # Database — наш класс для работы с SQLite.
    db = Database()

    # ------------------------------------------------------------------
    # 3. Инициализация базы данных
    # ------------------------------------------------------------------
    # Создаём таблицу tasks, если её ещё нет.
    # run() — асинхронный метод, который выполняет функцию
    # в отдельном потоке (чтобы не блокировать event loop).
    await db.start()

    logger.info("База данных инициализирована")

    # ------------------------------------------------------------------
    # 4. Подключение роутера с хендлерами
    # ------------------------------------------------------------------
    # Подключаем роутер, в котором зарегистрированы все команды.
    dp.include_router(handlers_router)

    # ------------------------------------------------------------------
    # 5. Запуск polling
    # ------------------------------------------------------------------
    logger.info("Бот запущен! Нажмите Ctrl+C для остановки.")

    # start_polling — асинхронный метод, который запускает
    # бесконечный цикл опроса Telegram API.
    # bot=bot — объект бота, который будет использоваться.
    # skip_updates=True — пропускает обновления, полученные
    # пока бот был выключен (чтобы не дублировать сообщения).
    # db=db — кладём объект базы данных в workflow data.
    # Благодаря этому каждый обработчик получает db автоматически
    # через параметр `db: Database` в своём определении.
    try:
        await dp.start_polling(bot, skip_updates=True, db=db)
    finally:
        # При остановке (например, по Ctrl+C) закрываем бота
        # и освобождаем ресурсы базы данных.
        logger.info("Бот остановлен. Закрытие...")
        await db.close()
        await bot.session.close()


# ===================================================================
# Точка входа
# ===================================================================

if __name__ == "__main__":
    # run() запускает асинхронную функцию main().
    asyncio.run(main())
